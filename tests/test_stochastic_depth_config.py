"""
`parse_config.validate_config` rejects `stochastic_depth > 0` in every table
that carries the key.

Three reasons, all read from the code rather than measured:

    * broccoli's `EncoderBlock` and our `DecoderBlock` drop a branch with a 0/1
      mask and never divide the kept branches by `keep_prob`, while eval runs
      every branch at full weight. Training and eval run different networks.
    * Under post-norm a dropped block is not the identity: each join still
      applies `RMSNorm(x)`.
    * The causal speaker reruns its stack once per symbol, so every symbol of a
      message would be generated by a differently-dropped network.

See docs/architecture.md.

Runnable without pytest:  python tests/test_stochastic_depth_config.py
"""

import os
import tempfile

import pytest

import _bootstrap  # noqa: F401

import parse_config


# The four tables DEFAULT.toml gives the key, per dataset after the overlay.
TABLES = (
    "sender_feature_model",
    "sender_language_model",
    "receiver_feature_model",
    "receiver_language_model",
)


def _config_for(dataset, extra=""):
    """`get_config` for one dataset, so the `[birds.*]` overlay is applied."""
    with tempfile.NamedTemporaryFile("w", suffix=".toml", delete=False) as f:
        f.write(f'name = "test"\n[data]\ndataset = "{dataset}"\n{extra}\n')
        path = f.name
    try:
        return parse_config.get_config(path)
    finally:
        os.unlink(path)


@pytest.mark.parametrize("dataset", ["../data/shapeworld", "../data/cub"])
def test_the_key_lives_in_exactly_the_four_tables(dataset):
    """
    Pins the coverage the scan relies on: if a fifth table gains the key it is
        checked anyway, but this says so.
    """
    config = _config_for(dataset)

    found = {
        table
        for table, section in config.items()
        if isinstance(section, dict) and "stochastic_depth" in section
    }
    assert found == set(TABLES)


@pytest.mark.parametrize("dataset", ["../data/shapeworld", "../data/cub"])
def test_the_defaults_validate(dataset):
    config = _config_for(dataset)
    for table in TABLES:
        assert config[table]["stochastic_depth"] == 0


@pytest.mark.parametrize("dataset", ["../data/shapeworld", "../data/cub"])
@pytest.mark.parametrize("table", TABLES)
def test_a_nonzero_rate_is_rejected_in_every_table(dataset, table):
    with pytest.raises(parse_config.InvalidConfig) as e:
        _config_for(dataset, f"[{table}]\nstochastic_depth = 0.1")

    message = str(e.value)
    assert f"`{table}.stochastic_depth = 0.1`" in message
    assert "keep_prob" in message
    assert "once per symbol" in message


def test_an_unknown_table_carrying_the_key_is_rejected_too():
    """
    The scan reads every table rather than a list, so a stack added later is
        covered without editing `validate_config`.
    """
    config = parse_config.get_config()
    config["some_new_stack"] = {"stochastic_depth": 0.05}

    with pytest.raises(parse_config.InvalidConfig):
        parse_config.validate_config(config)


def test_an_integer_zero_is_accepted():
    """TOML reads `0` as an int; it means the same as `0.0`."""
    config = parse_config.get_config()
    for table in TABLES:
        config[table]["stochastic_depth"] = 0

    parse_config.validate_config(config)


if __name__ == "__main__":
    import sys

    sys.exit(pytest.main([__file__, "-q"]))
